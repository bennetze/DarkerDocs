"""Validate versioning, generated sources and the exact runtime package."""
import hashlib
import json
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parent.parent
RUNTIME_FILES = {
    'manifest.json', 'INSTALL.txt', 'diagnostics.html', 'diagnostics.js', 'diagnostics.css',
    'shared/core.js', 'shared/themes.css', 'content/content.js', 'content/content.css',
    'content/renderer.js', 'content/renderer.bundle.js',
    'popup/popup.html', 'popup/popup.js', 'popup/popup.css',
    'assets/Roboto.ttf', 'assets/Roboto-OFL.txt',
    *(f'assets/icon-{size}.png' for size in (16, 32, 48, 64, 128)),
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def verify_source():
    manifest = json.loads((ROOT / 'extension/manifest.json').read_text())
    package = json.loads((ROOT / 'package.json').read_text())
    lock = json.loads((ROOT / 'package-lock.json').read_text())
    version = manifest['version']
    assert package['version'] == lock['version'] == lock['packages']['']['version'] == version, 'Version mismatch'
    assert f'DarkerDocs {version}' in (ROOT / 'extension/INSTALL.txt').read_text(), 'Stale installation version'
    assert f'**Version {version}**' in (ROOT / 'README.md').read_text(), 'Stale README version'
    assert manifest['permissions'] == ['storage'] and 'background' not in manifest, 'Unexpected permission or worker'
    expected = {'https://docs.google.com/' + app + '/*' for app in ('document', 'spreadsheets', 'presentation', 'forms')}
    assert set(manifest['content_scripts'][1]['matches']) == expected, 'Unexpected origins'
    assert set(manifest.get('host_permissions', [])) <= expected, 'Unexpected host permissions'
    expected_bundle = '// Generated by scripts/build.py; edit core.js and renderer.js.\n' + '\n'.join(
        (ROOT / 'extension' / name).read_text() for name in ('shared/core.js', 'content/renderer.js'))
    assert (ROOT / 'extension/content/renderer.bundle.js').read_text() == expected_bundle, 'Stale MAIN bundle'
    actual = {str(path.relative_to(ROOT / 'extension')) for path in (ROOT / 'extension').rglob('*')
              if path.is_file() and not any(part.startswith('.') for part in path.relative_to(ROOT / 'extension').parts)}
    assert actual == RUNTIME_FILES, f'Unexpected/missing runtime files: {actual ^ RUNTIME_FILES}'
    return version


def verify_package():
    version = verify_source()
    archive = ROOT / 'artifacts' / f'DarkerDocs-{version}.zip'
    with ZipFile(archive) as zipped:
        names = zipped.namelist()
        assert len(names) == len(set(names)) and set(names) == RUNTIME_FILES, 'Unexpected ZIP entries'
        for name in names:
            assert zipped.read(name) == (ROOT / 'extension' / name).read_bytes(), f'ZIP mismatch: {name}'
    checksum = digest(archive.read_bytes())
    assert archive.with_suffix('.sha256').read_text() == f'{checksum}  {archive.name}\n', 'Checksum mismatch'
    metadata = json.loads(archive.with_suffix('.verification.json').read_text())
    assert metadata == package_metadata(version, archive), 'Stale verification metadata'
    return version, checksum


def package_metadata(version, archive):
    return {'version': version, 'archive': archive.name, 'sha256': digest(archive.read_bytes()),
            'files': {name: digest((ROOT / 'extension' / name).read_bytes()) for name in sorted(RUNTIME_FILES)}}


if __name__ == '__main__':
    version, checksum = verify_package()
    print(f'DarkerDocs {version}: {len(RUNTIME_FILES)} ZIP entries match source; SHA-256 {checksum}')
