root=Path(__file__).resolve().parent.parent
sources=[root/'extension/shared/core.js',root/'extension/content/renderer.js']
(root/'extension/content/renderer.bundle.js').write_text('// Generated by scripts/build.py; edit core.js and renderer.js.\n'+'\n'.join(p.read_text() for p in sources))
